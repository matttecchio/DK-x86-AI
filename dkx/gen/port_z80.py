# Generate dkx/z80.h + dkx/z80.cpp from MAME 0.264 src/devices/cpu/z80/z80.{h,cpp}: the opcode code is copied verbatim,
# only the device-framework hooks are replaced (memory access -> board functions, callbacks -> no-ops).
import re, sys, os
SRC = os.path.join(os.environ.get("MAMESRC", os.path.expanduser("~/tools/mamesrc/mame-mame0264")), "src/devices/cpu/z80")
OUT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
h = open(f"{SRC}/z80.h").read().split("\n")
c = open(f"{SRC}/z80.cpp").read().split("\n")

# header: the PROTOTYPES macro and everything from it to the end of the class, minus framework members
i0 = next(i for i, l in enumerate(h) if l.startswith("#define PROTOTYPES"))
i1 = next(i for i, l in enumerate(h) if l.startswith("DECLARE_DEVICE_TYPE(Z80"))
body = []
for l in h[i0 - 1:i1]:
    if re.search(r"address_space_config|memory_access<|devcb_|^\s*// address spaces", l): continue
    body.append(l.replace("virtual ", "").replace(" override", ""))
hdr = ["// Generated by gen/port_z80.py from MAME 0.264 z80.h (BSD-3-Clause, Juergen Buchmueller). Do not edit.",
       "#pragma once", '#include "sched.h"', "",
       "u8 z80_mem_rd(u16 a); void z80_mem_wr(u16 a, u8 v); u8 z80_io_rd(u16 a); void z80_io_wr(u16 a, u8 v);", "",
       "struct z80_device : Exec {",
       "	void start(); void reset(); void execute_run(); void execute_set_input(int inputnum, int state);",
       "	u16 pc() const { return m_pc.w.l; }"] + body
hdr = "\n".join(hdr).replace("#undef PROTOTYPES\n", "")
open(f"{OUT}/z80.h", "w").write(hdr + "\n")

# body: macros/tables/opcodes .. nomreq_addr (stop before the NSC800 code), then start/reset/run
j0 = next(i for i, l in enumerate(c) if l.startswith("#define HAS_LDAIR_QUIRK"))
j1 = next(i for i, l in enumerate(c) if l.startswith("void nsc800_device::take_interrupt_nsc800"))
k0 = next(i for i, l in enumerate(c) if l.startswith("void z80_device::device_start"))
k1 = next(i for i, l in enumerate(c) if l.startswith("void nsc800_device::device_start"))
r0 = next(i for i, l in enumerate(c) if l.startswith("void z80_device::device_reset"))
r1 = next(i for i, l in enumerate(c) if l.startswith("void nsc800_device::device_reset"))
e0 = next(i for i, l in enumerate(c) if l.startswith("inline void z80_device::execute_cycles"))
e1 = next(i for i, l in enumerate(c) if l.startswith("void nsc800_device::check_interrupts"))
src = "\n".join(c[j0:j1] + c[k0:k1] + c[r0:r1] + c[e0:e1])
subs = [
    (r"m_halt_cb\([^;]*\);", "(void)0;"), (r"m_refresh_cb\([^;]*\);", "(void)0;"), (r"m_nomreq_cb\([^;]*\);", "(void)0;"),
    (r"m_irqack_cb\([^;]*\);", "(void)0;"), (r"daisy_call_reti_device\(\);", "(void)0;"),
    (r"device_z80daisy_interface \*intf = daisy_get_irq_device\(\);", "void *intf = nullptr;"),
    (r"\(intf != nullptr\) \? intf->z80daisy_irq_ack\(\) : standard_irq_callback\(0, m_pc\.w\.l\)", "0xff"),
    (r"translate_memory_address\(([^()]*(?:\([^()]*\))?[^()]*)\)", r"(\1)"),
    (r"m_data\.read_byte", "z80_mem_rd"), (r"m_opcodes\.read_byte", "z80_mem_rd"), (r"m_args\.read_byte", "z80_mem_rd"),
    (r"m_data\.write_byte", "z80_mem_wr"), (r"m_io\.read_byte", "z80_io_rd"), (r"m_io\.write_byte", "z80_io_wr"),
    (r"debugger_instruction_hook\([^;]*\);", "(void)0;"),
    (r"void z80_device::device_start\(\)", "void z80_device::start()"),
    (r"void z80_device::device_reset\(\)", "void z80_device::reset()"),
    (r"\tspace\(AS_PROGRAM\)\.cache\(m_args\);\n.*\n.*\n.*specific\(m_io\);\n", ""),
    (r"set_icountptr\(m_icount\);", "icountptr = &m_icount; m_m1_cycles = 4; m_memrq_cycles = 3; m_iorq_cycles = 4;"),
    (r"\n\tsave_item\([^\n]*", ""), (r"\n\tstate_add[^;]*;", ""),
    (r"\t\tif \(daisy_chain_present\(\)\)\n[^\n]*\n", ""), (r"\tcase Z80_INPUT_LINE_WAIT:\n[^\n]*\n[^\n]*\n", ""),
    (r"case Z80_INPUT_LINE_BUSRQ:", "case LINE_BUSRQ:"), (r"case INPUT_LINE_NMI:", "case LINE_NMI:"), (r"case INPUT_LINE_IRQ0:", "case LINE_IRQ0:"),
]
for a, b in subs:
    src, n = re.subn(a, b, src)
    if n == 0: print("WARNING: no match for", a, file=sys.stderr)
pre = ["// Generated by gen/port_z80.py from MAME 0.264 z80.cpp (BSD-3-Clause, Juergen Buchmueller). Do not edit.",
       '#include "z80.h"', "#include <utility>",
       "#define LOGINT(...) do {} while (0)", "#define LOGUNDOC(...) do {} while (0)", "#define logerror(...) do {} while (0)",
       "#define tag() \"\"", ""]
open(f"{OUT}/z80.cpp", "w").write("\n".join(pre) + src + "\n")
print("ok")
