# Generate dkx/mcs48.h + dkx/mcs48.cpp from MAME 0.264 src/devices/cpu/mcs48/mcs48.{h,cpp} (MB8884 = 8035-class part used by DK).
# Opcode handlers and tables are copied verbatim; framework hooks become board functions.
import re, sys, os
SRC = os.path.join(os.environ.get("MAMESRC", os.path.expanduser("~/tools/mamesrc/mame-mame0264")), "src/devices/cpu/mcs48")
OUT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
h = open(f"{SRC}/mcs48.h").read().split("\n")
c = open(f"{SRC}/mcs48.cpp").read().split("\n")

# header: expander_op enum + the protected member section of mcs48_cpu_device
e0 = next(i for i, l in enumerate(h) if "enum expander_op" in l)
e1 = next(i for i in range(e0, len(h)) if h[i].strip().startswith("};"))
m0 = next(i for i, l in enumerate(h) if "typedef void (mcs48_cpu_device::*mcs48_ophandler)();" in l)
m1 = next(i for i in range(m0, len(h)) if h[i].startswith("};"))
keep = []
skip = re.compile(r"address_space_config|memory_access<|devcb_|clock_update_delegate|required_shared_ptr|virtual |mcs48_cpu_device\(const machine_config|"
                  r"m_opcode_table;|s_upi41_opcodes|s_i8021_opcodes|s_i8022_opcodes|m_regptr;|// Memory spaces|// device|// construction")
for l in h[m0:m1]:
    if skip.search(l): continue
    if re.search(r"\{ return m_(program|data|io)\.|\{ m_(data|io)\.|m_port_in_cb|m_port_out_cb|m_test_in_cb|m_bus_in_cb|m_bus_out_cb|m_prog_out_cb", l): continue
    keep.append(l.replace("protected:", ""))
hdr = ["// Generated by gen/port_mcs48.py from MAME 0.264 mcs48.h (BSD-3-Clause, Dan Boris, Mirko Buffoni, Aaron Giles, Couriersud). Do not edit.",
       "#pragma once", '#include "sched.h"', "", "typedef u32 offs_t;",
       "u8 snd_rom_rd(u16 a); u8 snd_ext_rd(u8 a); void snd_ext_wr(u8 a, u8 v); u8 snd_port_rd(int p); void snd_port_wr(int p, u8 v);",
       "int snd_test_rd(int t); u8 snd_bus_rd(); void snd_bus_wr(u8 v);", "",
       "struct mcs48_cpu_device : Exec {"] + h[e0:e1 + 1] + [
       "	void start(); void device_reset(); void execute_run(); void execute_set_input(int inputnum, int state);",
       "	u8 m_ram[64]; uint8_t *m_regptr;",
       "	uint8_t program_r(offs_t a) { return snd_rom_rd(a); }",
       "	uint8_t ram_r(offs_t a) { return m_ram[a & 0x3f]; }",
       "	void ram_w(offs_t a, uint8_t v) { m_ram[a & 0x3f] = v; }",
       "	uint8_t ext_r(offs_t a) { return snd_ext_rd(a); }",
       "	void ext_w(offs_t a, uint8_t v) { snd_ext_wr(a, v); }",
       "	uint8_t port_r(offs_t a) { return snd_port_rd(a); }",
       "	void port_w(offs_t a, uint8_t v) { snd_port_wr(a, v); }",
       "	int test_r(offs_t a) { return snd_test_rd(a); }",
       "	uint8_t bus_r() { return snd_bus_rd(); }",
       "	void bus_w(uint8_t v) { snd_bus_wr(v); }",
       "	void prog_w(int v) {}"] + keep + ["};"]
open(f"{OUT}/mcs48.h", "w").write("\n".join(hdr) + "\n")

d0 = next(i for i, l in enumerate(c) if l.startswith("#define TIMER_ENABLED"))
d1 = next(i for i, l in enumerate(c) if l.startswith("#define R7")) + 1
f0 = next(i for i, l in enumerate(c) if l.startswith("uint8_t mcs48_cpu_device::opcode_fetch"))
f1 = next(i for i, l in enumerate(c) if l.startswith("void mcs48_cpu_device::device_config_complete"))
r0 = next(i for i, l in enumerate(c) if l.startswith("void mcs48_cpu_device::device_reset"))
r1 = next(i for i, l in enumerate(c) if "upi41_master_r - master CPU data/status" in l) - 1
x0 = next(i for i, l in enumerate(c) if l.startswith("void mcs48_cpu_device::execute_set_input"))
src = "\n".join(c[d0:d1] + c[f0:f1] + c[r0:r1] + c[x0:])
# drop the UPI-41 / i802x opcode tables (they reference handlers we keep anyway, but we only need the 8048 one)
src = re.sub(r"const mcs48_cpu_device::mcs48_ophandler mcs48_cpu_device::s_(upi41|i8021|i8022)_opcodes\[256\] =\n\{.*?\n\};\n", "", src, flags=re.S)
subs = [
    (r"standard_irq_callback\([^;]*\);", "(void)0;"), (r"debugger_instruction_hook\([^;]*\);", "(void)0;"),
    (r"\(this->\*m_opcode_table\[opcode\]\)\(\);", "(this->*s_mcs48_opcodes[opcode])();"),
    (r"if \(!m_t0_clk_func\.isnull\(\)\)\n\t\tm_t0_clk_func\(0\);", ""),
    (r"m_program\.read_byte", "program_r"), (r"\n#define OP\(_a\)", "\n#undef OP\n#define OP(_a)"),
    (r"&m_dataptr\[", "&m_ram["),
    (r"\tif \(!m_t0_clk_func\.isnull\(\)\)\n\t\tm_t0_clk_func\(clock\(\) / 3\);\n\telse\n\t\t", "\t"),
    (r"case MCS48_INPUT_IRQ:", "case LINE_IRQ0:"), (r"\t\tcase MCS48_INPUT_EA:\n[^\n]*\n[^\n]*\n", ""),
]
for a, b in subs:
    src, n = re.subn(a, b, src)
    if n == 0: print("WARNING: no match for", a, file=sys.stderr)
pre = ["// Generated by gen/port_mcs48.py from MAME 0.264 mcs48.cpp (BSD-3-Clause, Dan Boris, Mirko Buffoni, Aaron Giles, Couriersud). Do not edit.",
       '#include "mcs48.h"', "#define BIT(x, n) (((x) >> (n)) & 1)", "#define logerror(...) do {} while (0)",
       "#define LOG(...) do {} while (0)", "#define fatalerror(...) do {} while (0)", ""]
open(f"{OUT}/mcs48.cpp", "w").write("\n".join(pre) + src + "\n")
print("ok")
